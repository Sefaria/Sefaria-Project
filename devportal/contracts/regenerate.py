"""Regenerate the golden files in ``devportal/contracts/golden/`` (PLAN.md §2.5).

    python -m devportal.contracts.regenerate operations          # rewrite golden/operations.json
    python -m devportal.contracts.regenerate operations --check  # exit 1 if it is stale
    python -m devportal.contracts.regenerate all [--check]       # every registered golden
    python -m devportal.contracts.regenerate --list

A regenerated golden is a reviewed change, never a way to make a test pass.

To add a golden, write a producer that returns ``{relative path under golden/: text}`` and register it in
``GOLDENS`` with ``register``. Producers import what they need lazily so one broken area does not stop the
others. No Django import.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parent
GOLDEN = CONTRACTS / "golden"

Producer = Callable[[], dict[str, str]]
GOLDENS: dict[str, tuple[str, Producer]] = {}


def register(name: str, description: str):
    def decorator(fn: Producer) -> Producer:
        GOLDENS[name] = (description, fn)
        return fn

    return decorator


def dump_json(data) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


@register("operations", "golden/operations.json: title, description, method, path, tag, deprecated of every operation")
def operations() -> dict[str, str]:
    return {"operations.json": dump_json(operations_golden_document())}


def operations_golden_document() -> dict:
    """The full content of golden/operations.json, from ``docs/openAPI.json``."""
    from devportal.spec import load_spec

    data = load_spec().operations_golden()
    return {
        "$comment": (
            "Generated by `python -m devportal.contracts.regenerate operations` from docs/openAPI.json "
            "(PLAN.md §2.5, §2.7). Asserted by pytest (devportal/tests/pure/spec_golden_test.py) and Vitest. "
            "title = operation.summary or the path item's summary; description = operation.description only; "
            "tag = the operation's first tag; method in lower case. Do not edit by hand."
        ),
        **data,
    }


@register("markdown", "golden/markdown/*.html: the server renderer's HTML for each Markdown construct fixture (C4)")
def markdown() -> dict[str, str]:
    from devportal.markdown.golden import fixtures, golden_path, pretty, render_fixture

    return {f"markdown/{golden_path(f).name}": pretty(render_fixture(f).html) for f in fixtures()}


def run(names: list[str], *, check: bool) -> list[str]:
    """Write (or, with ``check``, compare) the goldens of ``names``; returns the stale relative paths."""
    stale = []
    for name in names:
        _, producer = GOLDENS[name]
        for rel, text in producer().items():
            target = GOLDEN / rel
            current = target.read_text(encoding="utf-8") if target.exists() else None
            if current == text:
                continue
            stale.append(rel)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(text, encoding="utf-8")
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m devportal.contracts.regenerate", description=__doc__.split("\n\n")[0]
    )
    parser.add_argument("names", nargs="*", help=f"goldens to regenerate: {', '.join(GOLDENS)} or all")
    parser.add_argument("--check", action="store_true", help="only report stale goldens; exit 1 if any")
    parser.add_argument("--list", action="store_true", help="list the registered goldens")
    args = parser.parse_args(argv)

    if args.list or not args.names:
        for name, (description, _) in GOLDENS.items():
            print(f"{name}\t{description}")
        return 0 if args.list else 2
    names = list(GOLDENS) if "all" in args.names else args.names
    unknown = [n for n in names if n not in GOLDENS]
    if unknown:
        parser.error(f"unknown golden(s): {', '.join(unknown)}")

    stale = run(names, check=args.check)
    verb = "stale" if args.check else "rewritten"
    for rel in stale:
        print(f"{verb}: golden/{rel}")
    if not stale:
        print("up to date")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
