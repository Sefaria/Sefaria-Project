def get_user_id_list():
    user_emails = get_user_emails()
    ids = []

    for email in user_emails:
        up = UserProfile(email=email)
        if up:
            ids.append(up.id)
    return ids


def get_all_public_sheets():
    collection = db.sheets

    # Query to filter documents
    query = {"status": "public"}
    projection = {"owner": 1}

    # Fetch documents based on the query
    results = collection.find(query, projection)

    # Convert the results to a list (optional)
    documents = list(results)

    print(f"Total public sheets: {len(documents)}")

    return documents


