import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildLegacyStaticCss, cssHash } from "./legacy-css";
import { LEGACY_STATIC_CSS } from "./legacy-css.gen";
import { LEGACY_STATIC_CSS_HASH } from "./legacy-css-hash.gen";

const STATIC_DIR = join(__dirname, "..", "..", "..", "..", "static");
const GEN = join(__dirname, "legacy-css.gen.ts");
const GEN_HASH = join(__dirname, "legacy-css-hash.gen.ts");
const HEADER = "// Generated by src/lib/static-page/legacy-css.test.ts from static/css (UPDATE_LEGACY_CSS=1 npm test -- legacy-css): do not edit.\n";

/** The generated module's text for a stylesheet. */
const genModule = (css: string) =>
  `${HEADER}// The legacy static-page stylesheets scoped to #staticContentWrapper (legacy-css.ts), served by src/routes/static-page-styles.$.ts.\n` +
  `export const LEGACY_STATIC_CSS = ${JSON.stringify(css)};\n`;
/** The hash on its own (the page's <link> needs it; the stylesheet itself stays on the server). */
const genHashModule = (css: string) => `${HEADER}export const LEGACY_STATIC_CSS_HASH = ${JSON.stringify(cssHash(css))};\n`;

// @feature STA-001
describe("the static pages' legacy stylesheet (legacy-css.gen.ts)", () => {
  // the repository's static/css is there in a full checkout (CI, development); the reader's image is built without it
  const haveSources = existsSync(join(STATIC_DIR, "css", "static.css"));

  it.runIf(haveSources)("is the scoped copy of today's static/css (regenerate with UPDATE_LEGACY_CSS=1)", () => {
    const css = buildLegacyStaticCss((name) => readFileSync(join(STATIC_DIR, name), "utf8"));
    if (process.env.UPDATE_LEGACY_CSS) {
      writeFileSync(GEN, genModule(css));
      writeFileSync(GEN_HASH, genHashModule(css));
    }
    expect(LEGACY_STATIC_CSS === css, "static/css changed: run UPDATE_LEGACY_CSS=1 npm test -- legacy-css").toBe(true);
    expect(LEGACY_STATIC_CSS_HASH).toBe(cssHash(css));
  });

  it("styles nothing outside the static page's wrapper", () => {
    const rules = LEGACY_STATIC_CSS.replace(/\/\*[\s\S]*?\*\//g, "").replace(/@(?:font-face|(?:-[a-z]+-)?keyframes)[^{]*\{(?:[^{}]|\{[^{}]*\})*\}/g, "");
    let selectors = 0;
    for (const m of rules.matchAll(/(?:^|[{}])\s*([^{}@;]+)\{/g)) {
      for (const sel of m[1]!.split(/,(?![^()]*\))/).map((s) => s.trim()).filter(Boolean)) {
        // a keyframe step inside @keyframes is not a selector (handled above); everything else starts at the wrapper
        expect(sel.startsWith("#staticContentWrapper"), sel).toBe(true);
        selectors++;
      }
    }
    expect(selectors).toBeGreaterThan(500);
  });

  it("keeps static.css's rules for the static pages", () => {
    expect(LEGACY_STATIC_CSS).toContain("#staticContentWrapper .static .inner {");
    expect(LEGACY_STATIC_CSS).toContain("#staticContentWrapper #aboutSidebar a {");
    expect(LEGACY_STATIC_CSS).toContain("--dark-grey: #666666;");
    // s2.css's links inherit their colour (the About sidebar's grey), and font-awesome's font is addressed from its own folder
    expect(LEGACY_STATIC_CSS).toMatch(/#staticContentWrapper a,\s*#staticContentWrapper a:hover \{\s*color: inherit;/);
    expect(LEGACY_STATIC_CSS).toContain("url('/static/font-awesome/fonts/fontawesome-webfont.woff2?v=4.6.3')");
  });
});
