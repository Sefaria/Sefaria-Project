#!/usr/bin/env node
// Writes a step-definition stub for every sentence in the behavior specs that has no step yet.
//
// Runs in CI when product pushes a spec (.github/workflows/bdd-stubs.yaml), so the engineer is
// handed a branch where every new sentence already has a stub. Each stub throws "not implemented",
// so generation passes and the new scenarios fail: the "red" state the engineer starts from.
// Process: e2e-tests/feature-specs/README.md.
//
// Stubs for features/<area>/<name>.feature go to steps/<area>/<name>.steps.ts (appended if the
// file exists). A sentence missing from several features gets one stub, in the first file.
//
// Usage:
//   node build/ci/bdd-stubs/generate-step-stubs.cjs           write stubs, print what was written
//   node build/ci/bdd-stubs/generate-step-stubs.cjs --check   print what would be written; exit 1 if anything
// Options (for testing against specs outside the repo):
//   --config <file>         BDD Playwright config (default playwright.bdd.config.ts)
//   --features-root <dir>   default e2e-tests/feature-specs/features
//   --steps-root <dir>      default e2e-tests/feature-specs/steps (must contain fixtures.ts)
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const argv = process.argv.slice(2);
const opt = (name, dflt) => {
  const i = argv.indexOf(name);
  return i >= 0 ? argv[i + 1] : dflt;
};
const CHECK = argv.includes('--check');
const CONFIG = opt('--config', 'playwright.bdd.config.ts');
const FEATURES_ROOT = path.resolve(opt('--features-root', 'e2e-tests/feature-specs/features'));
const STEPS_ROOT = path.resolve(opt('--steps-root', 'e2e-tests/feature-specs/steps'));

function collectMissingSteps() {
  const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'bdd-stubs-')), 'missing.jsonl');
  const bddCli = path.join(path.dirname(require.resolve('playwright-bdd/package.json')), 'dist/cli/index.js');
  const res = spawnSync(
    process.execPath,
    ['-r', path.join(__dirname, 'capture-missing-steps.cjs'), bddCli, 'test', '--config', CONFIG],
    { env: { ...process.env, BDD_MISSING_STEPS_OUT: out }, stdio: ['ignore', 'inherit', 'inherit'] }
  );
  if (res.status !== 0) {
    console.error(
      '\nbddgen failed for a reason other than missing steps (see above), for example a Gherkin\n' +
        'syntax error in a spec or a broken step file. No stubs were written.'
    );
    process.exit(res.status || 1);
  }
  if (!fs.existsSync(out)) return [];
  return fs
    .readFileSync(out, 'utf8')
    .split('\n')
    .filter(Boolean)
    .map((l) => JSON.parse(l));
}

function targetFileFor(featureUri) {
  const abs = path.resolve(featureUri);
  const rel = path.relative(FEATURES_ROOT, abs);
  if (rel.startsWith('..')) throw new Error(`Feature outside ${FEATURES_ROOT}: ${abs}`);
  return path.join(STEPS_ROOT, rel.replace(/\.feature$/, '.steps.ts'));
}

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function stubCode(step) {
  const args = ['{ visitor }', ...step.params.map((t, i) => `arg${i === 0 ? '' : i}: ${t}`)];
  if (step.extraArg === 'dataTable') args.push('dataTable: DataTable');
  if (step.extraArg === 'docString') args.push('docString: string');
  const said = `${step.gherkinKeyword} ${step.text}`;
  return [
    `${step.keyword}(${quote(step.expression)}, async (${args.join(', ')}) => {`,
    `  // Step: ${said}`,
    `  // From: ${path.relative(process.cwd(), path.resolve(step.location))}`,
    `  throw new Error(${quote(`Step not implemented yet: ${said}`)});`,
    `});`,
  ].join('\n');
}

function fixturesImportPath(file) {
  let rel = path.relative(path.dirname(file), path.join(STEPS_ROOT, 'fixtures'));
  if (!rel.startsWith('.')) rel = './' + rel;
  return rel.split(path.sep).join('/');
}

function renderFile(file, steps, featureRel) {
  const keywords = [...new Set(steps.map((s) => s.keyword))];
  const needsDataTable = steps.some((s) => s.extraArg === 'dataTable');
  const body = steps.map(stubCode).join('\n\n') + '\n';

  if (!fs.existsSync(file)) {
    return [
      `// Step stubs for ${featureRel}, generated by CI (build/ci/bdd-stubs).`,
      `// Each stub throws until it is implemented, so its scenarios fail ("red"). Implement each one`,
      `// through the page objects (e2e-tests/feature-specs/README.md, "Writing steps"), move steps`,
      `// other features can reuse to common.steps.ts, and delete this comment when done.`,
      needsDataTable ? `import { DataTable } from 'playwright-bdd';` : null,
      `import { ${['Given', 'When', 'Then'].filter((k) => keywords.includes(k)).join(', ')} } from '${fixturesImportPath(file)}';`,
      '',
      body,
    ]
      .filter((l) => l !== null)
      .join('\n');
  }

  // Existing file: append, and make sure the fixtures import names every keyword used.
  let src = fs.readFileSync(file, 'utf8');
  const importRe = /import\s*\{([^}]*)\}\s*from\s*'([^']*fixtures)';/;
  const m = src.match(importRe);
  if (m) {
    const names = new Set(m[1].split(',').map((s) => s.trim()).filter(Boolean));
    keywords.forEach((k) => names.add(k));
    src = src.replace(importRe, `import { ${[...names].join(', ')} } from '${m[2]}';`);
  } else {
    src = `import { ${keywords.join(', ')} } from '${fixturesImportPath(file)}';\n` + src;
  }
  if (needsDataTable && !/\bDataTable\b.*from 'playwright-bdd'/.test(src)) {
    src = `import { DataTable } from 'playwright-bdd';\n` + src;
  }
  return src.replace(/\s*$/, '\n\n') + `// Stubs added by CI (build/ci/bdd-stubs) for ${featureRel}.\n` + body;
}

function main() {
  const missing = collectMissingSteps();
  // One stub per expression: a cucumber expression matches whichever keyword the spec used.
  const seen = new Set();
  const byFile = new Map();
  for (const step of missing.sort((a, b) => a.location.localeCompare(b.location, 'en', { numeric: true }))) {
    if (seen.has(step.expression)) continue;
    seen.add(step.expression);
    const file = targetFileFor(step.featureUri ?? step.location.replace(/:\d+:\d+$/, ''));
    if (!byFile.has(file)) byFile.set(file, []);
    byFile.get(file).push(step);
  }

  if (byFile.size === 0) {
    console.log('Every step in the specs has a definition. No stubs needed.');
    return;
  }
  for (const [file, steps] of byFile) {
    const featureRel = path.relative(process.cwd(), path.resolve(steps[0].featureUri ?? ''));
    const relFile = path.relative(process.cwd(), file);
    console.log(`${CHECK ? 'Would write' : 'Wrote'} ${steps.length} stub(s) to ${relFile}:`);
    steps.forEach((s) => console.log(`  ${s.gherkinKeyword} ${s.text}`));
    if (!CHECK) {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, renderFile(file, steps, featureRel));
    }
  }
  if (CHECK) process.exit(1);
}

main();
