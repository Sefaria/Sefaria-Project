// Generates src/styles/readme-tokens.css from the custom properties measured on live
// (docs/dev-portal/research/reference/data/css-vars-computed-live.json). Contract C5.
//
//   node scripts/readme-tokens.ts            write the file
//   node scripts/readme-tokens.ts --check    exit 1 when the committed file is stale
//
// Also takes --project-color-primary and --project-color-inverse (#612854, #fff) from
// docs/dev-portal/research/site/root-css-vars-computed.json.
//
// Rules: every live name becomes --rm-<kebab-case name>; Font Awesome's --fa-* are dropped; ReadMe's
// round(15px * pow(1.2, n), 1px) type scale is resolved to pixels. Live sets the properties on <html> and
// overrides some on four containers; each becomes a block here, holding only what differs from its parent:
//   html → :root;  .rm-ReadMe → .dp-rm-app;  inside it, header → .dp-rm-header,
//   #ReferencePlayground → .dp-rm-playground,  .rm-PlaygroundRequest → .dp-rm-request-card.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PACKAGE = resolve(import.meta.dirname, '..');
const SOURCE = 'docs/dev-portal/research/reference/data/css-vars-computed-live.json';
// The project colours come from Sefaria's custom CSS, captured on a docs page; the reference capture lacks them.
const PROJECT_SOURCE = 'docs/dev-portal/research/site/root-css-vars-computed.json';
const PROJECT_KEYS = ['--project-color-primary', '--project-color-inverse'];
const OUTPUT = resolve(PACKAGE, 'src/styles/readme-tokens.css');

type Vars = Record<string, string>;
interface Live {
  html: Vars;
  rmReadMe: Vars;
  header: Vars;
  playground: Vars;
  reqCard: Vars;
}

export function kebab(name: string): string {
  return name
    .replace(/^--/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()
    .replace(/-+/g, '-');
}

function px(n: number): string {
  return `${Math.round(n)}px`;
}

/** Resolves ReadMe's modular type scale, the only computed expressions in the capture. */
export function resolveValue(value: string): string {
  const scale = /^round\((\d+(?:\.\d+)?)px \* pow\((\d+(?:\.\d+)?), (-?\d+)\), 1px\)$/;
  const floored = /^max\((\d+)px, (round\(.*\))\)$/;
  const m = floored.exec(value);
  if (m?.[2] !== undefined) {
    return px(Math.max(Number(m[1]), parseFloat(resolveValue(m[2]))));
  }
  const s = scale.exec(value);
  if (s) return px(Number(s[1]) * Number(s[2]) ** Number(s[3]));
  return value;
}

/** Kebab-cases the names of one scope and resolves values. Aliases (--lightGray, --light-gray) must agree. */
function normalize(vars: Vars): Vars {
  const out: Vars = {};
  for (const [name, value] of Object.entries(vars)) {
    if (name.startsWith('--fa-')) continue;
    const key = `--rm-${kebab(name)}`;
    const resolved = resolveValue(value);
    if (key in out && out[key] !== resolved) throw new Error(`${name} and an alias both map to ${key}`);
    out[key] = resolved;
  }
  return out;
}

function block(selector: string, vars: Vars, parent: Vars): string {
  const lines = Object.entries(vars)
    .filter(([name, value]) => parent[name] !== value)
    .map(([name, value]) => `  ${name}: ${value};`);
  return lines.length === 0 ? '' : `${selector} {\n${lines.join('\n')}\n}\n`;
}

export function render(live: Live, project: Vars): string {
  const projectVars = Object.fromEntries(PROJECT_KEYS.map((key) => [key, project[key] ?? '']));
  if (Object.values(projectVars).includes('')) throw new Error(`${PROJECT_SOURCE} lacks ${PROJECT_KEYS.join(', ')}`);
  const html = normalize({ ...live.html, ...projectVars });
  const app = { ...html, ...normalize(live.rmReadMe) };
  return [
    '/*',
    ' * readme-tokens.css: custom properties measured on live developers.sefaria.org (contract C5).',
    ` * GENERATED by scripts/readme-tokens.ts from ${SOURCE}`,
    ` * and ${PROJECT_SOURCE}. Do not edit by hand.`,
    ' * Live wins for the reference and docs chrome (PLAN §2.8). Put .dp-rm-app on the shell root, and the',
    ' * other scope classes on the header, the playground column and the request card, as on live.',
    ' */',
    block(':root', html, {}),
    block('.dp-rm-app', app, html),
    block('.dp-rm-header', normalize(live.header), app),
    block('.dp-rm-playground', normalize(live.playground), app),
    block('.dp-rm-request-card', normalize(live.reqCard), app),
  ]
    .filter((part) => part !== '')
    .join('\n');
}

export function readSources(): [Live, Vars] {
  const read = (path: string) => JSON.parse(readFileSync(resolve(PACKAGE, '..', path), 'utf8')) as unknown;
  return [read(SOURCE) as Live, read(PROJECT_SOURCE) as Vars];
}

export const OUTPUT_PATH = OUTPUT;

if (import.meta.main) {
  const css = render(...readSources());
  if (process.argv.includes('--check')) {
    if (readFileSync(OUTPUT, 'utf8') !== css) {
      console.error(`${OUTPUT} is stale; run node scripts/readme-tokens.ts`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, css);
  }
}
