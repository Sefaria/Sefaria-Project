def replace_block(text: str, block: str) -> str:
    if START.split(" (")[0] in text and END in text:
        return re.sub(re.escape(START.split(" (")[0]) + r".*?" + re.escape(END), lambda _: block, text, count=1, flags=re.S)
    if not text.strip():
        return block + "\n"
    return text.rstrip() + "\n\n" + block + "\n"


def write(path: pathlib.Path, initial: str, block: str, check: bool) -> bool:
    old = path.read_text() if path.exists() else None
    new = replace_block(old if old is not None else initial, block)
    # the generated date alone does not count as a change
    strip = lambda s: re.sub(r"_Generated \d{4}-\d{2}-\d{2}", "_Generated", s or "")
    if strip(new) == strip(old):
        return False
    if not check:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new)
    return True


def index_table(by: dict, status: dict) -> str:
    rows = [START, "", "| Domain | Area | Features (core) | New client done | Product | Architecture | Owner |", "|---|---|---|---|---|---|---|"]
    for domain, lst in AREAS:
        for slug, title in lst:
            items = by[slug]
            done = sum(1 for f in items if status.get(f["id"], {}).get("status") in DONE)
            owner = "unassigned"
            pm = FUTURE / slug / "product.md"
            if pm.exists():
                m = re.search(r"^owner:\s*(.+)$", pm.read_text(), re.M)
                owner = m[1].strip() if m else owner
            core = sum(1 for f in items if f["tier"] == "core")
            rows.append(f"| {domain} | **{title}** (`{slug}`) | {len(items)} ({core}) | {done} | [product]({slug}/product.md) | [architecture]({slug}/architecture.md) | {owner} |")
    rows += ["", f"_Generated {TODAY} by `tools/seed.py`._", "", END]
    return "\n".join(rows)


def areas_reference(by: dict, status: dict) -> str:
    """The skill's taxonomy (claude-tag/.../references/areas.md): what each area covers and where its code lives on each branch."""
    out = [START, "", "# The 29 product areas", "",
           "Generated from the Feature Atlas by `docs/reader-future/tools/seed.py`. For each area: what it covers (its atlas groups),",
           "its atlas ID prefixes, and the files that implement it most on each branch. Use it to place a message in its area(s).", ""]
    for domain, lst in AREAS:
        out += [f"## {domain}", ""]
        for slug, title in lst:
            items = by[slug]
            groups = list(dict.fromkeys(f.get("group") or "" for f in items if f.get("group")))
            prefixes = sorted({f["id"].split("-")[0] for f in items})
            legacy = collections.Counter(r.split(":")[0].strip() for f in items for r in (f.get("refs") or []))
            new = collections.Counter(status[f["id"]]["by"].strip().split(" ")[0].rstrip(",")
                                      for f in items if status.get(f["id"], {}).get("by"))
            out += [f"### {title} — `{slug}`", "",
                    f"- **Covers:** {'; '.join(groups) or '—'}",
                    f"- **Atlas IDs:** {', '.join(p + '-' for p in prefixes)} ({len(items)} features)",
                    f"- **Legacy (`master`):** {', '.join(f'`{p}`' for p, _ in legacy.most_common(5)) or '—'}",
                    f"- **New (`reader-next`, under `reader-next/`):** {', '.join(f'`{p}`' for p, _ in new.most_common(5)) or 'not built yet'}", ""]
    out += [f"_Generated {TODAY} by `tools/seed.py`._", "", END]
    return "\n".join(out)


def main() -> int:
    check = "--check" in sys.argv
    by, status = load()
    changed = []
    for _, lst in AREAS:
        for slug, title in lst:
            if write(FUTURE / slug / "product.md", front(slug, "product") + PRODUCT_BODY.format(title=title), product_baseline(slug, by[slug], status), check):
                changed.append(f"{slug}/product.md")
            if write(FUTURE / slug / "architecture.md", front(slug, "architecture") + ARCH_BODY.format(title=title), architecture_baseline(slug, by[slug], status), check):
                changed.append(f"{slug}/architecture.md")
    readme = FUTURE / "README.md"
    if readme.exists() and write(readme, "", index_table(by, status), check):
        changed.append("README.md")
    ref = FUTURE / "claude-tag" / "capture-future-spec" / "skills" / "capture-future-spec" / "references" / "areas.md"
    if write(ref, "", areas_reference(by, status), check):
        changed.append("claude-tag/.../references/areas.md")
    print(("Out of date: " if check else "Updated: ") + (", ".join(changed) if changed else "nothing"))
    return 1 if (check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
