#!/usr/bin/env python3
"""
Seed and refresh the future-reader specification (docs/reader-future/) from the Feature Atlas.

    python3 docs/reader-future/tools/seed.py            # create missing files, refresh every BASELINE block
    python3 docs/reader-future/tools/seed.py --check    # exit 1 if a BASELINE block is out of date (CI / routine use)

For each of the atlas's 29 product areas it keeps two files, `<area>/product.md` and `<area>/architecture.md`. Each file has
sections owned by the channel (written by Claude Tag from the #reader-future conversation, skill `capture-future-spec`) and one
generated block between `<!-- BASELINE:START -->` and `<!-- BASELINE:END -->`. This script only ever rewrites that block (and the
index table in README.md); it never touches the channel's sections, so it is safe to re-run after the atlas changes.

Sources (all on this branch): reader-next/docs/features/features.json (the atlas: what sefaria.org does, legacy code refs),
reader-next/docs/features/rebuild-status.json (what the new client has built, and where).
"""
from __future__ import annotations

import collections
import datetime
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]          # repository root
FUTURE = ROOT / "docs" / "reader-future"
ATLAS = ROOT / "reader-next" / "docs" / "features"
GH = "https://github.com/Sefaria/Sefaria-Project/blob"
LEGACY_BRANCH, NEW_BRANCH = "master", "reader-next"

# The atlas's own grouping and names (reader-next/docs/features/tools/build.py, AREAS): keep the two in step.
AREAS = [
    ("Reader", [("reader-shell", "Reader shell & panels"), ("text-display", "Text display & reading settings"), ("text-types", "Text types & special cases"), ("connections", "Connections & resources sidebar"), ("versions", "Versions & translations")]),
    ("Library & discovery", [("library-nav", "Library navigation"), ("book-pages", "Book pages"), ("topics", "Topics"), ("calendars", "Calendars"), ("search", "Search & autocomplete")]),
    ("Voices (sheets & community)", [("sheets-view", "Sheets: viewing"), ("sheets-editor", "Sheets: editing & publishing"), ("collections", "Collections"), ("profile-social", "Profiles & social"), ("user-library", "Saved, history & notes"), ("notifications", "Notifications & email")]),
    ("Site & accounts", [("global-ui", "Global UI"), ("accounts", "Accounts & sign-in"), ("promotions", "Promotions & CMS"), ("static-pages", "Static pages"), ("i18n-a11y", "Language & accessibility"), ("ai", "AI features")]),
    ("Platform", [("routing", "URLs & routing"), ("platform-seo", "SSR, SEO & platform"), ("api-data", "Public API & data exports"), ("analytics", "Analytics"), ("linker-embeds", "Linker & embeds")]),
    ("Internal & legacy", [("admin-tools", "Admin & moderator tools"), ("legacy-pages", "Legacy pages")]),
]
TITLE = {slug: name for _, lst in AREAS for slug, name in lst}
DOMAIN = {slug: d for d, lst in AREAS for slug, _ in lst}
START, END = "<!-- BASELINE:START (generated by docs/reader-future/tools/seed.py — do not edit by hand) -->", "<!-- BASELINE:END -->"
TODAY = datetime.date.today().isoformat()
TIERS = ["core", "standard", "optional", "retire"]
DONE = {"done"}
GAP = {"todo", "partial", "deferred", None}


def load():
    feats = json.load(open(ATLAS / "features.json"))
    status = json.load(open(ATLAS / "rebuild-status.json"))
    areas = {f["area"] for f in feats}
    if areas != set(TITLE):
        sys.exit(f"Atlas areas and seed.py AREAS differ: {sorted(areas ^ set(TITLE))}")
    by = collections.defaultdict(list)
    for f in feats:
        by[f["area"]].append(f)
    return by, status


def legacy_link(ref: str) -> str:
    m = re.match(r"^([\w.\-/]+)(?::(\d+)(?:\s*[-–]\s*(\d+))?)?$", ref.strip())
    if not m:
        return f"`{ref}`"
    url = f"{GH}/{LEGACY_BRANCH}/{m[1]}" + (f"#L{m[2]}" + (f"-L{m[3]}" if m[3] else "") if m[2] else "")
    return f"[`{ref}`]({url})"


def new_link(path: str) -> str:
    p = path.strip().split(" ")[0].rstrip(",")
    return f"[`{p}`]({GH}/{NEW_BRANCH}/reader-next/{p})" if p.startswith(("src/", "server/", "e2e/", "docs/", "scripts/")) else f"`{p}`"


def esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def product_baseline(slug: str, items: list, status: dict) -> str:
    tiers = collections.Counter(f["tier"] for f in items)
    groups = collections.Counter(f["group"] for f in items)
    flagged = [f for f in items if f["status"] in ("broken", "unused", "legacy")]
    out = [START, "", "## Baseline: what sefaria.org does today", "",
           f"From the Feature Atlas (`reader-next/docs/features`, area `{slug}`): **{len(items)} features** — "
           + ", ".join(f"{t} {tiers[t]}" for t in TIERS if tiers[t]) + ". Tiers are the audit's proposal (core: can't launch without it; "
           "standard: parity, can follow; optional: niche or rethink; retire: unused, broken or superseded).", "",
           "Feature groups: " + "; ".join(f"{g} ({n})" for g, n in groups.most_common()) + ".", ""]
    for tier in TIERS:
        rows = [f for f in items if f["tier"] == tier]
        if not rows:
            continue
        out += [f"### {tier.capitalize()} ({len(rows)})", "", "| ID | Feature | What it does |", "|---|---|---|"]
        out += [f"| {f['id']} | {esc(f['name'])} | {esc(f['summary'])} |" for f in sorted(rows, key=lambda f: f["id"])]
        out.append("")
    if flagged:
        out += ["### Flags from the audit (not to port as-is)", ""]
        out += [f"- **{f['id']}** {esc(f['name'])} — {f['status']}" for f in sorted(flagged, key=lambda f: f["id"])]
        out.append("")
    out += [f"_Generated {TODAY}. Full behaviour for every ID: `reader-next/docs/features/FEATURES.md` and the atlas page._", "", END]
    return "\n".join(out)


def architecture_baseline(slug: str, items: list, status: dict) -> str:
    refs = collections.Counter()
    for f in items:
        for r in f.get("refs", []):
            refs[re.sub(r":.*$", "", r.strip())] += 1
    inv = collections.Counter(f.get("src", "").split("#")[0] for f in items if f.get("src", "").startswith("inv_"))
    st = collections.Counter(status.get(f["id"], {}).get("status") for f in items)
    impl = collections.Counter()
    for f in items:
        for p in re.split(r",\s*", status.get(f["id"], {}).get("by", "") or ""):
            if p.strip():
                impl[p.strip()] += 1
    gaps = [f for f in items if status.get(f["id"], {}).get("status") in GAP and f["tier"] in ("core", "standard")]
    order = ["done", "partial", "todo", "deferred", "replaced", "n/a", None]
    label = {None: "not started", "n/a": "not applicable"}
    out = [START, "", "## Baseline: the two clients today", "",
           f"### Legacy client (`{LEGACY_BRANCH}`)", "",
           "Where the atlas found this area's behaviour (files cited by its features, most-cited first):", ""]
    out += [f"- {legacy_link(p)} ({n})" for p, n in refs.most_common(15)]
    if inv:
        out += ["", "Long-form audit write-up: " + ", ".join(f"`reader-next/docs/features/{p}`" for p, _ in inv.most_common()) + "."]
    out += ["", f"### New client (`{NEW_BRANCH}`, folder `reader-next/`)", "",
            "Rebuild status of this area's features: " + ", ".join(f"{label.get(s, s)} {st[s]}" for s in order if st[s]) + ".", ""]
    if impl:
        out += ["Implemented in (most features first):", ""]
        out += [f"- {new_link(p)} ({n})" for p, n in impl.most_common(15)]
        out.append("")
    if gaps:
        out += [f"### Gaps: core and standard features not done ({len(gaps)})", "", "| ID | Tier | Feature | Rebuild status |", "|---|---|---|---|"]
        out += [f"| {f['id']} | {f['tier']} | {esc(f['name'])} | {label.get(status.get(f['id'], {}).get('status'), status.get(f['id'], {}).get('status'))} |"
                for f in sorted(gaps, key=lambda f: (TIERS.index(f["tier"]), f["id"]))]
        out.append("")
    out += [f"_Generated {TODAY} from the atlas and `rebuild-status.json`. Architecture of each client as a whole: `reader-next/docs/ARCHITECTURE.md`._", "", END]
    return "\n".join(out)


def front(slug: str, kind: str) -> str:
    return "\n".join(["---", f"area: {slug}", f"title: {TITLE[slug]}", f"domain: {DOMAIN[slug]}", f"document: {kind}",
                      "owner: unassigned", "status: baseline  # baseline → exploring → proposed → agreed", f"updated: {TODAY}", "---", ""])


